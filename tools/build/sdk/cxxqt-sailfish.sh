# Cross-compiles one CXX-Qt crate (a Qt 6 app or a static library)
# for a Sailfish target, inside the Sailfish platform SDK container, and
# stages its outputs in <out-dir>.
#
#   cxxqt-sailfish.sh [--target-name SailfishOS-5.2.0.15-aarch64] \
#       <crate-dir> <out-dir> [extra cargo build args...]
#
# Stages into <out-dir>:
#   - every binary the crate builds, and every shared library (cdylib): a
#     Qt 6 app is one, executable too, that its spec installs as
#     /usr/bin/<app> (e.g. libshipwright_shoal_keys.so; see
#     tools/keel-launcher/link_sailfishapp.rs);
#   - every static library (lib<crate>.a), plus, for a static library, the
#     CXX-Qt export tree <out-dir>/cxxqt-export (headers and the
#     initializers object a CMake/qmake build links), with its symlinks into
#     the cargo directory replaced by copies so it stands alone.
#
# Why outside mb2: the SDK's Rust is 1.75 and CXX-Qt 0.10 needs 1.85, so this
# uses cargo-sailfish.sh (rustup toolchain, SDK cross gcc, target sysroot);
# there is no cargo in specs (README.md, "Spec convention for Rust packages").
#
# CXX-Qt finds Qt through `qmake -query` and runs moc, rcc, qmltyperegistrar
# and qmlcachegen. The target's Qt 6 (Chum, installed into the target by
# sdk.sh) has aarch64 tools, so:
#   - qmake is a generated script answering with the target qmake6's values
#     (queried once through sb2), header and library paths mapped into the
#     target sysroot and tool paths pointing at the wrappers below;
#   - moc, rcc, qmltyperegistrar and qmlcachegen are wrappers that run the
#     target's tools through sb2 (qemu). Under sb2 those tools can write
#     their outputs with mode 000 (QSaveFile cannot stat its descriptor: sb2
#     logs "Path not found for FD ... statx()"), so each wrapper makes any
#     unreadable file named in its arguments readable again.
#
# Environment:
#   CARGO_TARGET_DIR   cargo output (default: <repo>/target). Crates sharing
#                      it reuse cxx-qt-lib's C++ build, which dominates the
#                      build time (its moc runs under qemu).
#   CXXQT_TOOLS_DIR    where the qmake stand-in and wrappers are generated
#                      (default: $CARGO_TARGET_DIR/sailfish-qt/<target>). Keep
#                      it stable: cargo rebuilds cxx-qt-lib when QMAKE moves.
set -euo pipefail

target_name=${SAILFISH_TARGET:-SailfishOS-5.2.0.15-aarch64}
if [ "${1:-}" = "--target-name" ]; then
    target_name=$2
    shift 2
fi
[ $# -ge 2 ] || { sed -n '5,9p' "$0" >&2; exit 2; }
crate=$(cd "$1" && pwd)
mkdir -p "$2"
out=$(cd "$2" && pwd)
shift 2

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)
# SAILFISH_NATIVE=1 (tools/build/native): inside a native Sailfish OS root,
# the target's Qt tools run as they are; no sb2 wrappers, no qmake stand-in.
native=${SAILFISH_NATIVE:-0}
sysroot=/srv/mer/targets/$target_name
[ "$native" = 1 ] && sysroot=
[ "$native" = 1 ] || [ -d "$sysroot" ] || { echo "no such SDK target: $sysroot" >&2; exit 2; }
case "$target_name" in
    *-aarch64) qt=/usr/lib64/qt6 ;;
    *-armv7hl) qt=/usr/lib/qt6 ;;
    *) echo "unsupported target $target_name" >&2; exit 2 ;;
esac
if [ ! -x "$sysroot$qt/bin/qmake6" ] || [ ! -x "$sysroot$qt/libexec/qmlcachegen" ]; then
    echo "Qt 6 development tools are missing in $sysroot (qmake6, qmlcachegen)." >&2
    echo "Install them into the target (sdk.sh does): sb2 -t $target_name -m sdk-install -R" \
         "zypper in qt6-qtbase-devel qt6-qtdeclarative-devel" >&2
    exit 2
fi

export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$repo/target}
mkdir -p "$CARGO_TARGET_DIR"
CARGO_TARGET_DIR=$(cd "$CARGO_TARGET_DIR" && pwd)
if [ "$native" = 1 ]; then
echo "== CXX-Qt $crate for $target_name, native (Qt $("$qt/bin/qmake6" -query QT_VERSION))"
export QMAKE=$qt/bin/qmake6
else
tools=${CXXQT_TOOLS_DIR:-$CARGO_TARGET_DIR/sailfish-qt/$target_name}
mkdir -p "$tools"

for tool in moc rcc qmltyperegistrar qmlcachegen; do
    cat > "$tools/$tool.new" <<WRAP
#!/bin/sh
# Generated by tools/build/sdk/cxxqt-sailfish.sh: runs the target's $tool
# through sb2, then makes outputs written with mode 000 readable.
HOME='$HOME'
export HOME
/usr/bin/sb2 -t '$target_name' '$qt/libexec/$tool' "\$@"
status=\$?
for arg in "\$@"; do
    f=\${arg#*=}
    if [ -f "\$f" ] && [ ! -r "\$f" ]; then chmod 0644 "\$f"; fi
done
exit \$status
WRAP
    chmod +x "$tools/$tool.new"
    mv "$tools/$tool.new" "$tools/$tool"
done

# qmake stand-in. qt-build-utils runs it with a cleared environment, so the
# answers are baked in.
query=$(sb2 -t "$target_name" "$qt/bin/qmake6" -query)
{
    echo '#!/bin/sh'
    echo '# Generated by tools/build/sdk/cxxqt-sailfish.sh from the target qmake6 -query.'
    # shellcheck disable=SC2016 # literal $2 for the generated script
    echo 'case "$2" in'
    while IFS= read -r line; do
        key=${line%%:*}
        value=${line#*:}
        case "$key" in
            *LIBEXECS*|*BINS*) value=$tools ;;
            QT_VERSION|QT_HOST_PREFIX*|QMAKE_*|QT_SYSROOT*) ;;
            *) case "$value" in /*) value=$sysroot$value ;; esac ;;
        esac
        printf "    '%s') echo '%s' ;;\n" "$key" "$value"
    done <<<"$query"
    echo "    *) exit 1 ;;"
    echo 'esac'
} > "$tools/qmake.new"
chmod +x "$tools/qmake.new"
mv "$tools/qmake.new" "$tools/qmake"
echo "== CXX-Qt $crate for $target_name (Qt $("$tools/qmake" -query QT_VERSION))"

export QMAKE=$tools/qmake
fi
export QT_VERSION_MAJOR=6
export CARGO_INCREMENTAL=0

# A static library is linked by a C++ build, which also needs CXX-Qt's
# headers and initializers: export them.
pkg=$(python3 - "$crate/Cargo.toml" <<'PY'
import sys, tomllib
with open(sys.argv[1], "rb") as f:
    m = tomllib.load(f)
p = m.get("package", {}).get("name", "")
staticlib = "staticlib" in m.get("lib", {}).get("crate-type", [])
print(p.replace("-", "_") if staticlib else "")
PY
)
if [ -n "$pkg" ]; then
    rm -rf "$out/cxxqt-export"
    export CXX_QT_EXPORT_DIR=$out/cxxqt-export
    export "CXX_QT_EXPORT_CRATE_$pkg=1"
fi

messages=$(mktemp)
trap 'rm -f "$messages"' EXIT
cd "$crate"
"$here/cargo-sailfish.sh" --target-name "$target_name" \
    build --release --locked --manifest-path "$crate/Cargo.toml" \
    --message-format=json-render-diagnostics "$@" > "$messages"

# Stage this crate's binaries, shared libraries and static libraries.
python3 - "$messages" "$crate/Cargo.toml" <<'PY' |
import json, sys
manifest = sys.argv[2]
for line in open(sys.argv[1]):
    try:
        msg = json.loads(line)
    except ValueError:
        continue
    if msg.get("reason") != "compiler-artifact" or msg.get("manifest_path") != manifest:
        continue
    kinds = msg["target"]["kind"]
    if "bin" in kinds and msg.get("executable"):
        print(msg["executable"])
    elif "cdylib" in kinds:
        print(*[f for f in msg["filenames"] if f.endswith(".so")], sep="\n")
    elif "staticlib" in kinds:
        print(*[f for f in msg["filenames"] if f.endswith(".a")], sep="\n")
PY
{ staged=0; while IFS= read -r artifact; do
    dest=$out/$(basename "$artifact")
    if [ ! "$artifact" -ef "$dest" ]; then
        cp -f "$artifact" "$dest"
    fi
    # Keel Actions files (ADR-0018) that the crate's build.rs wrote next to it.
    # (Staging into cargo's own output directory, as the specs' hooks do,
    # leaves them where they are.)
    if [ -d "$(dirname "$artifact")/keel-actions" ] && [ ! "$(dirname "$artifact")" -ef "$out" ]; then
        mkdir -p "$out/keel-actions"
        cp -rf "$(dirname "$artifact")/keel-actions/." "$out/keel-actions/"
    fi
    echo "staged: $dest"
    staged=$((staged + 1))
done
[ "$staged" -gt 0 ] || { echo "no binary or library built in $crate" >&2; exit 1; }; }

if [ -n "$pkg" ]; then
    test -f "$out/cxxqt-export/crates/$pkg/initializers.o"
    # The export tree links the cxx-qt and cxx-qt-lib headers into the cargo
    # target directory; copy them so the staged tree stands alone.
    for link in "$out/cxxqt-export/crates/$pkg/include"/*; do
        if [ -L "$link" ]; then
            resolved=$(readlink -f "$link")
            rm "$link"
            cp -r "$resolved" "$link"
        fi
    done
    echo "staged: $out/cxxqt-export"
fi
